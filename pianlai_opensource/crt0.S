# 文件名: crt0.S (JTAG 直加载版)
.section .text
.global _start

_start:
  # ==================================================
  # 1. 初始化 .data 段 (已移除)
  # ==================================================
  # 由于 link.ld 中去掉了 AT> 重定向，且 JTAG 直接将数据
  # 写入了 SRAM1，这里不再需要从 SRAM0 搬运数据。
  
  # ==================================================
  # 2. 清零 .bss 段 (保留)
  # ==================================================
  # 虽然 JTAG 可以写数据，但 BSS 段通常在烧录文件中不占用空间
  # 且 SRAM1 上电后其余部分可能是随机值，必须手动清零。
  la a0, _sbss      # .bss 起始地址
  la a1, _ebss      # .bss 结束地址

zero_bss_loop:
  bge a0, a1, zero_bss_done  # 如果 当前地址 >= 结束地址，完成
  sw  zero, 0(a0)            # 写入 0
  addi a0, a0, 4             # 指针 +4
  j   zero_bss_loop
zero_bss_done:
  
  # ==================================================
  # 3. 设置堆栈指针
  # ==================================================
  la sp, _stack_start

  # ==================================================
  # 4. 跳转到 main
  # ==================================================
  call main

  # 死循环兜底
inf_loop:
  j inf_loop