uint32_t pack_dina(uint8_t instruct, int8_t in0, int8_t in1, int8_t in2) {
    uint32_t d = 0;
    d |= (uint32_t)instruct;
    d |= ((uint32_t)(uint8_t)in0) << 8;
    d |= ((uint32_t)(uint8_t)in1) << 16;
    d |= ((uint32_t)(uint8_t)in2) << 24;
    return d;
}

